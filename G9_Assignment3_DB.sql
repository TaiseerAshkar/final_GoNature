DROP DATABASE IF EXISTS park_db;
CREATE DATABASE park_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE park_db;

-- ============================================================
--  SCHEMA
-- ============================================================
CREATE TABLE parks (
    id                    INT            AUTO_INCREMENT PRIMARY KEY,
    name                  VARCHAR(100)   NOT NULL,
    capacity              INT            NOT NULL,
    max_orders            INT            NOT NULL,
    visit_duration_hours  INT            NOT NULL DEFAULT 4,
    full_price            DECIMAL(10, 2) NOT NULL,
    created_at            TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_parks_capacity   CHECK (capacity > 0),
    CONSTRAINT chk_parks_max_orders CHECK (max_orders > 0),
    CONSTRAINT chk_parks_duration   CHECK (visit_duration_hours > 0),
    CONSTRAINT chk_parks_price      CHECK (full_price >= 0)
);

CREATE TABLE users (
    id          INT          AUTO_INCREMENT PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    first_name  VARCHAR(50)  NOT NULL,
    last_name   VARCHAR(50)  NOT NULL,
    email       VARCHAR(100) NOT NULL UNIQUE,
    role        ENUM('department_manager','park_manager','employee','service') NOT NULL,
    park_id     INT          NULL,
    created_at  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_park FOREIGN KEY (park_id) REFERENCES parks(id)
        ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE visitors (
    id_number   VARCHAR(20)  PRIMARY KEY,
    first_name  VARCHAR(50)  NOT NULL,
    last_name   VARCHAR(50)  NOT NULL,
    email       VARCHAR(100),
    phone       VARCHAR(20)
);

CREATE TABLE subscribers (
    subscriber_id  INT          AUTO_INCREMENT PRIMARY KEY,
    id_number      VARCHAR(20)  NOT NULL UNIQUE,
    first_name     VARCHAR(50)  NOT NULL,
    last_name      VARCHAR(50)  NOT NULL,
    email          VARCHAR(100) NOT NULL,
    phone          VARCHAR(20),
    credit_card    VARCHAR(20)  NULL,   -- optional: NULL means the customer chose to pay cash
    family_size    INT          NOT NULL DEFAULT 1,
    created_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_subscribers_family CHECK (family_size >= 1),
    CONSTRAINT fk_subscribers_visitor FOREIGN KEY (id_number) REFERENCES visitors(id_number)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE guides (
    id_number   VARCHAR(20)  PRIMARY KEY,
    first_name  VARCHAR(50)  NOT NULL,
    last_name   VARCHAR(50)  NOT NULL,
    email       VARCHAR(100),
    phone       VARCHAR(20),
    is_approved TINYINT(1)   NOT NULL DEFAULT 0,
    CONSTRAINT fk_guides_visitor FOREIGN KEY (id_number) REFERENCES visitors(id_number)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE orders (
    id           INT          AUTO_INCREMENT PRIMARY KEY,
    visitor_id   VARCHAR(20)  NOT NULL,
    park_id      INT          NOT NULL,
    visit_date   DATE         NOT NULL,
    visit_time   TIME         NOT NULL,
    num_visitors INT          NOT NULL,
    order_type   VARCHAR(20)  NOT NULL,
    status       ENUM('pending','confirmed','cancelled','completed','no_show')
                              NOT NULL DEFAULT 'pending',
    entry_time   TIMESTAMP    NULL DEFAULT NULL,
    exit_time    TIMESTAMP    NULL DEFAULT NULL,
    created_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    reminder_sent TINYINT(1)   NOT NULL DEFAULT 0,
    CONSTRAINT chk_orders_visitors CHECK (num_visitors >= 1),
    CONSTRAINT chk_orders_type_count CHECK (
        (order_type = 'individual' AND num_visitors = 1) OR
        (order_type IN ('family','group') AND num_visitors BETWEEN 2 AND 15)
    ),
    CONSTRAINT fk_orders_park FOREIGN KEY (park_id) REFERENCES parks(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_orders_visitor FOREIGN KEY (visitor_id) REFERENCES visitors(id_number)
        ON DELETE CASCADE ON UPDATE CASCADE,
    INDEX idx_orders_park_date (park_id, visit_date),
    INDEX idx_orders_visitor   (visitor_id),
    INDEX idx_orders_status    (status)
);

CREATE TABLE waiting_list (
    id                    INT          AUTO_INCREMENT PRIMARY KEY,
    visitor_id            VARCHAR(20)  NOT NULL,
    park_id               INT          NOT NULL,
    visit_date            DATE         NOT NULL,
    visit_time            TIME         NOT NULL,
    num_visitors          INT          NOT NULL,
    order_type            VARCHAR(20)  NOT NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'WAITING',
    order_id              INT          NULL DEFAULT NULL,
    notified_at           TIMESTAMP    NULL DEFAULT NULL,
    promoted_at           TIMESTAMP    NULL DEFAULT NULL,
    confirmation_deadline TIMESTAMP    NULL DEFAULT NULL,
    created_at            TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_wl_visitors CHECK (num_visitors >= 1),
    CONSTRAINT fk_wl_park FOREIGN KEY (park_id) REFERENCES parks(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_wl_visitor FOREIGN KEY (visitor_id) REFERENCES visitors(id_number)
        ON DELETE CASCADE ON UPDATE CASCADE,
    INDEX idx_wl_park_date (park_id, visit_date)
);

CREATE TABLE promotions (
    id               INT            AUTO_INCREMENT PRIMARY KEY,
    park_id          INT            NOT NULL,
    description      VARCHAR(255)   NOT NULL,
    discount_percent DOUBLE         NOT NULL,
    start_date       DATE           NOT NULL,
    end_date         DATE           NOT NULL,
    status           ENUM('PENDING','ACTIVE','REJECTED') NOT NULL DEFAULT 'PENDING',
    submitted_by     VARCHAR(50)    NOT NULL,
    created_at       TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_promo_percent CHECK (discount_percent >= 0 AND discount_percent <= 50),
    CONSTRAINT chk_promo_dates   CHECK (end_date >= start_date),
    CONSTRAINT fk_promo_park FOREIGN KEY (park_id) REFERENCES parks(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    INDEX idx_promo_park_status (park_id, status)
);

-- Park-settings change-request approval workflow (required by the server,
-- absent from the stock GoNature_DB.sql).
CREATE TABLE park_settings_requests (
    id                   INT            AUTO_INCREMENT PRIMARY KEY,
    park_id              INT            NOT NULL,
    requested_by         VARCHAR(50)    NOT NULL,
    capacity             INT            NOT NULL,
    max_orders           INT            NOT NULL,
    visit_duration_hours INT            NOT NULL,
    full_price           DECIMAL(10,2)  NOT NULL,
    status               ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
    requested_at         TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    reviewed_at          TIMESTAMP      NULL DEFAULT NULL,
    CONSTRAINT fk_psr_park FOREIGN KEY (park_id) REFERENCES parks(id)
        ON DELETE CASCADE ON UPDATE CASCADE
);

